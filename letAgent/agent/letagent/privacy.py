"""Privacy guards.

The agent only ever reads metrics JSON written by letAgent_runBatch.m. These
helpers make sure nothing that could identify a patient ends up in the
agent's state, logs or report, even by accident (for example a file path
inside a MATLAB error message).
"""
import re

ALIAS_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,31}$")
_PATH_RE = re.compile(r"([A-Za-z]:)?([\\/][^\s'\"<>|]+)+")
_LONGNUM_RE = re.compile(r"\d{6,}")
_DATE_RE = re.compile(r"(19|20)\d{2}[-_/.]?(0[1-9]|1[0-2])[-_/.]?(0[1-9]|[12]\d|3[01])")

BANNER = ("Contains dose metrics derived from the case named by its study alias. "
          "If this is a patient case, keep this file inside the hospital network and do not "
          "upload it to external services, including AI assistants, without privacy-office approval.")


class PrivacyError(ValueError):
    pass


def check_alias(alias):
    if not isinstance(alias, str) or not ALIAS_RE.match(alias):
        raise PrivacyError("Case alias must be a study code such as CNS_03 "
                           "(letters, digits, _ or -, max 32 characters, starting with a letter).")
    if _LONGNUM_RE.search(alias) or _DATE_RE.search(alias):
        raise PrivacyError("Case alias looks like it contains an ID number or a date; use a study code.")
    return alias


def scrub_text(text, max_len=300):
    """Remove file paths, long numbers and dates from free text (e.g. errors)."""
    if text is None:
        return ""
    text = str(text)
    text = _PATH_RE.sub("<path>", text)
    text = _DATE_RE.sub("<date>", text)
    text = _LONGNUM_RE.sub("<num>", text)
    return text[:max_len]


def scrub_run(run, allowed_strings):
    """Return a copy of a run result where every string that is not a known
    structure name, enum value or run id has been scrubbed."""
    def walk(x, key=None):
        if isinstance(x, dict):
            return {k: walk(v, k) for k, v in x.items()}
        if isinstance(x, list):
            return [walk(v, key) for v in x]
        if isinstance(x, str):
            if x in allowed_strings or (key == "runId" and re.match(r"^r\d{3,5}$", x)):
                return x
            return scrub_text(x)
        return x
    return walk(run)


# --------------------------------------------------------------------------
# Data classes and data-location guard
#
# Every case file declares what it holds:
#   "dataClass": "patient"    real patient data (also the default for source.type "matFile")
#   "dataClass": "synthetic"  generated by letAgent_makeCnsPhantom or similar
#   "dataClass": "public"     matRad phantoms, TCIA or other openly licensed data
#
# For patient cases letAgent refuses to run unless the case file, the source
# data and the work folder are all outside the code repository and outside
# every folder listed as connected to an AI assistant. The repository is a
# shared, AI-assisted workspace; patient data must never be placed in it.
# --------------------------------------------------------------------------
import os

DATA_CLASSES = ("patient", "synthetic", "public")
AI_FOLDERS_FILE = os.path.join("letAgent", "config", "ai_connected_folders.txt")
AI_FOLDERS_ENV = "LETAGENT_AI_FOLDERS"


def data_class(case):
    dc = case.get("dataClass")
    if dc is None:
        src = case.get("source", {})
        return "patient" if src.get("type") == "matFile" else "synthetic"
    if dc not in DATA_CLASSES:
        raise PrivacyError("dataClass must be one of {}.".format(", ".join(DATA_CLASSES)))
    if dc != "patient" and case.get("source", {}).get("type") == "matFile":
        # A .mat file can hold anything; only accept it as non-patient with an explicit note.
        if not case.get("dataClassNote"):
            raise PrivacyError("A case loaded from a .mat file is treated as patient data unless "
                               "dataClassNote says where the data comes from (e.g. 'TCIA GLIS-RT case 012').")
    return dc


def _norm(p):
    return os.path.normcase(os.path.realpath(os.path.abspath(os.path.expanduser(p))))


def _inside(path, root):
    path, root = _norm(path), _norm(root)
    return path == root or path.startswith(root.rstrip(os.sep) + os.sep)


def ai_folders(repo_root):
    """The repository plus every folder listed in letAgent/config/ai_connected_folders.txt
    and in the LETAGENT_AI_FOLDERS environment variable (os.pathsep-separated)."""
    roots = [repo_root]
    f = os.path.join(repo_root, AI_FOLDERS_FILE)
    if os.path.exists(f):
        with open(f) as fh:
            for line in fh:
                line = line.split("#", 1)[0].strip()
                if line:
                    roots.append(line)
    roots += [p for p in os.environ.get(AI_FOLDERS_ENV, "").split(os.pathsep) if p.strip()]
    return roots


def check_data_location(case, case_file, repo_root):
    """Raise PrivacyError if a patient case would read or write inside the repository
    or an AI-connected folder. Returns the case's data class."""
    dc = data_class(case)
    if dc != "patient":
        return dc
    proto = str(case.get("reb", {}).get("protocol", "")).strip()
    if not proto or "XX" in proto:
        raise PrivacyError("Patient case: set reb.protocol to your REB protocol number.")
    if not case.get("workDir"):
        raise PrivacyError("Patient case: set workDir explicitly to a folder on hospital storage.")
    work = case["workDir"]
    if not os.path.isabs(os.path.expanduser(work)):
        raise PrivacyError("Patient case: workDir must be an absolute path on hospital storage.")
    checks = [("case file", case_file), ("workDir", work)]
    src = case.get("source", {})
    if src.get("path"):
        checks.append(("source.path", src["path"]))
    for label, p in checks:
        for root in ai_folders(repo_root):
            if _inside(p, root):
                raise PrivacyError("Patient case: the {} is inside the code repository or a folder connected "
                                   "to an AI assistant ({}). Move it to hospital storage outside these folders."
                                   .format(label, "repository" if _norm(root) == _norm(repo_root) else "listed in "
                                           + AI_FOLDERS_FILE))
    return dc


def banner(case):
    if data_class(case) == "patient":
        return ("PATIENT DATA (REB protocol {}). Contains dose metrics derived from patient case {}. Keep this "
                "file on hospital storage. Do not share it, upload it or show it to any AI assistant."
                .format(case.get("reb", {}).get("protocol", "?"), case.get("alias", "?")))
    return "{} case: no patient data.".format(data_class(case).capitalize())
